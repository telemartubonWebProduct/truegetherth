// Makes the pictures of the four steps, shown on the slip of the home page:
//
//   node scripts/media/step-pictures.mjs [--replace]
//
// The sources (design/steps/source/, see the README beside them) are four small
// paintings in the manner of the page's opening picture, one for each step.
// This writes each at the widths the slip needs to public/media/steps-v1/, and
// the list the page reads to src/components/site/home/step-pictures.ts.
//
// Browsers keep these files for a year (next.config.ts), so a picture that has
// changed must not keep its name: it goes in a new folder (steps-v2…, `out` and
// `web` below). The script stops at a file that would come out different from
// the one already there; --replace lets it through, for a file that was never
// published.
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import sharp from "sharp";

const source = "design/steps/source";
const out = "public/media/steps-v1";
const web = "/media/steps-v1";
const data = "src/components/site/home/step-pictures.ts";
const replace = process.argv.includes("--replace");

/** In the order of the steps: the slip shows a picture once its step is done. */
const PICTURES = ["choose", "contact", "area", "install"];
/** The slip's picture is 264 pixels wide on a phone and 344 on a desktop: once and twice over, with room for a dense screen. */
const WIDTHS = [420, 840];

await mkdir(out, { recursive: true });
const written = [];
const pictures = [];
for (const [index, id] of PICTURES.entries()) {
  const file = path.join(source, `${index + 1}-${id}.png`);
  const { width, height } = await sharp(file).metadata();
  const files = [];
  for (const wide of WIDTHS) {
    const name = `${id}-${wide}.webp`;
    const bytes = await sharp(file).resize({ width: wide }).webp({ quality: 78, effort: 6 }).toBuffer();
    const target = path.join(out, name);
    const old = await readFile(target).catch(() => null);
    if (old && !old.equals(bytes) && !replace) {
      throw new Error(`${name} would change, and browsers keep it for a year: write to a new folder (steps-v2), or pass --replace if it was never published.`);
    }
    if (!old || !old.equals(bytes)) await writeFile(target, bytes);
    written.push(name);
    files.push({ src: `${web}/${name}`, width: wide });
    console.log(`${name.padEnd(22)} ${Math.round(bytes.length / 1024)} kB`);
  }
  const largest = WIDTHS[WIDTHS.length - 1];
  pictures.push({ id, width: largest, height: Math.round((largest * height) / width), files });
}
// What an earlier run left behind and this one does not use.
for (const file of await readdir(out)) if (!written.includes(file)) await rm(path.join(out, file));

await writeFile(
  data,
  `// Generated by scripts/media/step-pictures.mjs: do not edit by hand. To change a
// picture, replace its source in design/steps/source and run the script again.

export type StepPicture = {
  id: string;
  /** The largest file's size, for the page to keep the picture's room. */
  width: number;
  height: number;
  files: { src: string; width: number }[];
};

/** One picture for each step of "How it works", in the steps' order. */
export const stepPictures: StepPicture[] = ${JSON.stringify(pictures, null, 2)};
`,
);
console.log(`\nWrote ${data}`);
